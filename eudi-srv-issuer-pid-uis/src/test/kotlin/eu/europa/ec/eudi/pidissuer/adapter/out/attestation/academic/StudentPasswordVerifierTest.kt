package eu.europa.ec.eudi.pidissuer.adapter.out.attestation.academic

import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder
import kotlin.test.Test
import kotlin.test.assertEquals

class StudentPasswordVerifierTest {
    private val verifier = StudentPasswordVerifier()

    /** Hash de `pass123` generado por pgcrypto: `SELECT crypt('pass123', gen_salt('bf', 10))`. */
    private val pgcryptoHash = "\$2a\$10\$FWhPmeiDiAcHCyUNTxyMoekC89tkhoCjqU/FfkTxDSeuAnb5EN1IO"

    @Test
    fun `accepts a password that matches a hash generated by pgcrypto`() {
        assertEquals(PasswordCheck.VALID, verifier.verify("pass123", pgcryptoHash, legacyPlainPassword = null))
    }

    @Test
    fun `rejects a wrong password against a pgcrypto hash`() {
        assertEquals(PasswordCheck.INVALID, verifier.verify("pass124", pgcryptoHash, legacyPlainPassword = null))
        assertEquals(PasswordCheck.INVALID, verifier.verify("", pgcryptoHash, legacyPlainPassword = null))
    }

    @Test
    fun `accepts a password that matches a hash generated by the application`() {
        val hash = BCryptPasswordEncoder().encode("s3creta")
        assertEquals(PasswordCheck.VALID, verifier.verify("s3creta", hash, legacyPlainPassword = null))
    }

    @Test
    fun `falls back to the legacy plaintext password only when there is no hash`() {
        assertEquals(PasswordCheck.VALID_LEGACY, verifier.verify("vieja", storedHash = null, legacyPlainPassword = "vieja"))
        assertEquals(PasswordCheck.INVALID, verifier.verify("otra", storedHash = null, legacyPlainPassword = "vieja"))
    }

    @Test
    fun `the hash always wins over the legacy plaintext password`() {
        // La clave heredada coincide, pero el hash dice otra cosa: no hay acceso.
        assertEquals(PasswordCheck.INVALID, verifier.verify("vieja", pgcryptoHash, legacyPlainPassword = "vieja"))
        // Y con la clave del hash entra aunque la heredada sea distinta.
        assertEquals(PasswordCheck.VALID, verifier.verify("pass123", pgcryptoHash, legacyPlainPassword = "vieja"))
    }

    @Test
    fun `rejects a student with no stored password at all`() {
        assertEquals(PasswordCheck.INVALID, verifier.verify("lo-que-sea", storedHash = null, legacyPlainPassword = null))
    }

    @Test
    fun `rejects a malformed stored hash instead of failing`() {
        assertEquals(PasswordCheck.INVALID, verifier.verify("pass123", "esto-no-es-un-hash", legacyPlainPassword = null))
    }

    @Test
    fun `an unknown user is always rejected`() {
        assertEquals(PasswordCheck.INVALID, verifier.verifyUnknownUser("pass123"))
    }
}
